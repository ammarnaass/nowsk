    fun getItemsForCategory(categoryId: String): List<DhikrItem> {
        return DHIKR_ITEMS.filter { it.categoryId == categoryId }
    }

    fun searchAll(query: String): List<DhikrItem> {
        if (query.isBlank()) return emptyList()
        val q = query.trim().lowercase()
        return DHIKR_ITEMS.filter {
            it.title.lowercase().contains(q) ||
                    it.text.lowercase().contains(q) ||
                    it.categoryNameAr.lowercase().contains(q)
        }
    }
