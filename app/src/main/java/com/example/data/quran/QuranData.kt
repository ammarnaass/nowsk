    fun getSurah(number: Int): Surah? {
        return SURAHS.find { it.number == number }
    }

    fun getAyahs(surahNumber: Int): List<Ayah> {
        val specific = SURAH_VERSES_MAP[surahNumber]
        if (specific != null) return specific

        // Generates placeholder reading layout for other Surahs gracefully with full verses info
        val surah = getSurah(surahNumber) ?: return emptyList()
        val count = surah.versesCount.coerceAtMost(10)
        return (1..count).map { idx ->
            Ayah(
                surahNumber = surahNumber,
                ayahNumber = idx,
                text = "آيات سورة ${surah.nameAr} المباركة — الآية رقم $idx من ${surah.versesCount} آية."
            )
        }
    }

    fun searchQuran(query: String): List<Ayah> {
        if (query.isBlank()) return emptyList()
        val q = query.trim().lowercase()
        val results = mutableListOf<Ayah>()
        for ((_, ayahs) in SURAH_VERSES_MAP) {
            for (ayah in ayahs) {
                if (ayah.text.contains(q)) {
                    results.add(ayah)
                }
            }
        }
        return results
    }
