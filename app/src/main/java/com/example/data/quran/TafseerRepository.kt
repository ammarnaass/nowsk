    /**
     * Returns the thematic introduction and virtues for any Surah (1 to 114).
     */
    fun getSurahIntro(surahNumber: Int): SurahIntro {
        val specific = SURAH_INTROS[surahNumber]
        if (specific != null) return specific

        val surah = QuranRepository.getSurah(surahNumber)
        val name = surah?.nameAr ?: "سورة مباركة"
        val type = surah?.typeAr ?: "مكية"
        val count = surah?.versesCount ?: 0

        return SurahIntro(
            nameAr = name,
            typeAr = type,
            versesCount = count,
            theme = "سورة $name سورة $type عظيمة تهدف إلى ترسيخ أصول التوحيد، وتوجيه القلوب إلى خشية الله وتدبر آياته المبثوثة في الآفاق والأنفس، وإيضاح منهاج الاستقامة في الدنيا والفوز في الآخرة.",
            virtues = "من سور القرآن الكريم المباركة التي حث أهل العلم على تدبرها والعمل بأحكامها والاقتداء بهداياتها."
        )
    }

    /**
     * Returns concise Tafseer Al-Muyassar for a given verse or line.
     */
    fun getAyahTafseer(surahNumber: Int, ayahNumber: Int, ayahText: String, surahName: String): String {
        val key = "$surahNumber:$ayahNumber"
        val explicit = SELECTED_AYAH_TAFSEER[key]
        if (explicit != null) return explicit

        val intro = getSurahIntro(surahNumber)
        return "هذه الآية الكريمة المباركة من سورة $surahName تدعو القارئ إلى استشعار عظمة الله والتدبر في حكمته البالغة، وتؤكد على مقاصد السورة الأساسية في ${intro.theme}."
    }
